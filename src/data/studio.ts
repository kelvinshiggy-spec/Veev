export const getSession = (id: string) => SESSIONS.find((s) => s.id === id);

export function recommendSkill(c?: CheckIn): Session | undefined {
  if (!c) return undefined;
  const e = new Set(c.emotions);
  const pick = (id: string) => getSession(id);
  if (c.craving >= 6) return pick("urge-surfing");
  if (e.has("Angry") || e.has("Irritable")) return pick("anger");
  if (e.has("Lonely")) return pick("loneliness");
  if (e.has("Ashamed")) return pick("shame");
  if (e.has("Misunderstood")) return pick("check-the-facts");
  if (e.has("Anxious") || e.has("Overwhelmed") || e.has("Restless")) return pick("paced-breathing");
  if (e.has("Sad") || e.has("Empty")) return pick("opposite-action");
  if ((e.has("Excited") || e.has("Proud") || e.has("Happy")) && c.craving >= 3) return pick("handling-success");
  if (c.mood <= 2) return pick("grounding-54321");
  return undefined;
}
